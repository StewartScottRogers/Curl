using System.Numerics;

namespace Curl.Cryptography;

/// <summary>
/// A finite-field Diffie-Hellman group: a prime modulus p and a generator g. The named
/// groups are the ones curl's SSH and TLS backends offer - Oakley groups 1 and 2 (RFC 2409
/// section 6), MODP groups 14, 16 and 18 (RFC 3526), and <c>ffdhe2048</c> to
/// <c>ffdhe8192</c> (RFC 7919 appendix A), all with generator 2 - and
/// <see cref="TryCreate" /> accepts the group a server picks for SSH's
/// <c>diffie-hellman-group-exchange-*</c> (RFC 4419).
/// </summary>
/// <remarks>
/// A group is public data. <see cref="FiniteFieldDiffieHellman" /> computes in it.
/// </remarks>
public sealed class FiniteFieldDiffieHellmanGroup
{
    private readonly byte[] prime;
    private readonly byte[] generator;
    private readonly BigInteger primeValue;

    private FiniteFieldDiffieHellmanGroup(byte[] prime, byte[] generator)
    {
        this.prime = prime;
        this.generator = generator;
        primeValue = new BigInteger(prime, isUnsigned: true, isBigEndian: true);
        Modulus = new MontgomeryModulus(prime);
    }

    /// <summary>Oakley group 1, the 768-bit MODP group of RFC 2409 section 6.1 (SSH <c>diffie-hellman-group1-sha1</c>).</summary>
    public static FiniteFieldDiffieHellmanGroup Group1 { get; } = FromNamedPrime(Group1PrimeHex);

    /// <summary>Oakley group 2, the 1024-bit MODP group of RFC 2409 section 6.2.</summary>
    public static FiniteFieldDiffieHellmanGroup Group2 { get; } = FromNamedPrime(Group2PrimeHex);

    /// <summary>Group 14, the 2048-bit MODP group of RFC 3526 section 3 (SSH <c>diffie-hellman-group14-*</c>).</summary>
    public static FiniteFieldDiffieHellmanGroup Group14 { get; } = FromNamedPrime(Group14PrimeHex);

    /// <summary>Group 16, the 4096-bit MODP group of RFC 3526 section 5 (SSH <c>diffie-hellman-group16-sha512</c>).</summary>
    public static FiniteFieldDiffieHellmanGroup Group16 { get; } = FromNamedPrime(Group16PrimeHex);

    /// <summary>Group 18, the 8192-bit MODP group of RFC 3526 section 7 (SSH <c>diffie-hellman-group18-sha512</c>).</summary>
    public static FiniteFieldDiffieHellmanGroup Group18 { get; } = FromNamedPrime(Group18PrimeHex);

    /// <summary>TLS <c>ffdhe2048</c>, RFC 7919 appendix A.1.</summary>
    public static FiniteFieldDiffieHellmanGroup Ffdhe2048 { get; } = FromNamedPrime(Ffdhe2048PrimeHex);

    /// <summary>TLS <c>ffdhe3072</c>, RFC 7919 appendix A.2.</summary>
    public static FiniteFieldDiffieHellmanGroup Ffdhe3072 { get; } = FromNamedPrime(Ffdhe3072PrimeHex);

    /// <summary>TLS <c>ffdhe4096</c>, RFC 7919 appendix A.3.</summary>
    public static FiniteFieldDiffieHellmanGroup Ffdhe4096 { get; } = FromNamedPrime(Ffdhe4096PrimeHex);

    /// <summary>TLS <c>ffdhe6144</c>, RFC 7919 appendix A.4.</summary>
    public static FiniteFieldDiffieHellmanGroup Ffdhe6144 { get; } = FromNamedPrime(Ffdhe6144PrimeHex);

    /// <summary>TLS <c>ffdhe8192</c>, RFC 7919 appendix A.5.</summary>
    public static FiniteFieldDiffieHellmanGroup Ffdhe8192 { get; } = FromNamedPrime(Ffdhe8192PrimeHex);

    /// <summary>The prime p, big-endian, with no leading zero byte.</summary>
    public ReadOnlySpan<byte> Prime => prime;

    /// <summary>The generator g, big-endian, with no leading zero byte.</summary>
    public ReadOnlySpan<byte> Generator => generator;

    /// <summary>The length in bytes of p, and so of every public value and shared secret this group produces.</summary>
    public int PrimeLength => prime.Length;

    /// <summary>The Montgomery arithmetic modulo p.</summary>
    internal MontgomeryModulus Modulus { get; }

    /// <summary>
    /// Builds a group from a prime and generator a peer sent, as SSH's
    /// <c>SSH_MSG_KEX_DH_GEX_GROUP</c> carries them (RFC 4419 section 3), both big-endian
    /// with any leading zero bytes (an <c>mpint</c>'s sign byte) ignored.
    /// </summary>
    /// <returns>
    /// <c>false</c>, with <paramref name="group" /> <c>null</c>, when p is even or below
    /// 2^8, or g is not in 1 &lt; g &lt; p - 1; otherwise <c>true</c>. Whether p is large
    /// enough for the connection, and whether it is prime, is the protocol's check.
    /// </returns>
    public static bool TryCreate(
        ReadOnlySpan<byte> prime,
        ReadOnlySpan<byte> generator,
        [System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out FiniteFieldDiffieHellmanGroup? group)
    {
        group = null;
        var primeValue = new BigInteger(prime, isUnsigned: true, isBigEndian: true);
        var generatorValue = new BigInteger(generator, isUnsigned: true, isBigEndian: true);
        if (primeValue.IsEven || primeValue < 256 || generatorValue <= BigInteger.One || generatorValue >= primeValue - 1)
        {
            return false;
        }

        group = new FiniteFieldDiffieHellmanGroup(
            primeValue.ToByteArray(isUnsigned: true, isBigEndian: true),
            generatorValue.ToByteArray(isUnsigned: true, isBigEndian: true));
        return true;
    }

    /// <summary>
    /// Whether a peer's public value, big-endian of any length, lies in 1 &lt; y &lt; p - 1,
    /// the range RFC 7919 section 5.1 and RFC 4253 section 8 require. The value is public,
    /// so this check may branch.
    /// </summary>
    internal bool IsValidPublicValue(ReadOnlySpan<byte> publicValue)
    {
        var value = new BigInteger(publicValue, isUnsigned: true, isBigEndian: true);
        return value > BigInteger.One && value < primeValue - 1;
    }


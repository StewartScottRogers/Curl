    private readonly UInt128[] encryptionRoundKeys;

    private readonly UInt128[] decryptionRoundKeys;

    private bool disposed;

    /// <summary>Runs ARIA's key schedule on <paramref name="key" />.</summary>
    /// <exception cref="ArgumentException"><paramref name="key" /> is not 16, 24 or 32 bytes.</exception>
    public Aria(ReadOnlySpan<byte> key)
    {
        if (key.Length is not (16 or 24 or 32))
        {
            throw new ArgumentException($"ARIA needs a key of 16, 24 or 32 bytes; this is {key.Length}.", nameof(key));
        }

        int rounds = 12 + ((key.Length - 16) / 4);
        encryptionRoundKeys = new UInt128[rounds + 1];
        decryptionRoundKeys = new UInt128[rounds + 1];
        ExpandEncryptionRoundKeys(key, encryptionRoundKeys);
        decryptionRoundKeys[0] = encryptionRoundKeys[rounds];
        decryptionRoundKeys[rounds] = encryptionRoundKeys[0];
        for (int index = 1; index < rounds; index++)
        {
            decryptionRoundKeys[index] = Diffuse(encryptionRoundKeys[rounds - index]);
        }
    }

    /// <summary>The round keys ek1 to ek{n+1}; all zero after <see cref="Dispose" />.</summary>
    internal ReadOnlySpan<UInt128> EncryptionRoundKeys => encryptionRoundKeys;

    /// <summary>The round keys dk1 to dk{n+1}; all zero after <see cref="Dispose" />.</summary>
    internal ReadOnlySpan<UInt128> DecryptionRoundKeys => decryptionRoundKeys;

    /// <summary>Encrypts the one block <paramref name="source" /> into <paramref name="destination" />.</summary>
    /// <exception cref="ArgumentException">A span is not <see cref="BlockSize" /> bytes.</exception>
    /// <exception cref="ObjectDisposedException">The instance has been disposed.</exception>
    public void EncryptBlock(ReadOnlySpan<byte> source, Span<byte> destination)
    {
        RequireUsable(source.Length, destination.Length);
        TransformBlock(source, destination, encryptionRoundKeys);
    }

    /// <summary>Decrypts the one block <paramref name="source" /> into <paramref name="destination" />.</summary>
    /// <exception cref="ArgumentException">A span is not <see cref="BlockSize" /> bytes.</exception>
    /// <exception cref="ObjectDisposedException">The instance has been disposed.</exception>
    public void DecryptBlock(ReadOnlySpan<byte> source, Span<byte> destination)
    {
        RequireUsable(source.Length, destination.Length);
        TransformBlock(source, destination, decryptionRoundKeys);
    }

    /// <summary>Zeroes the round keys; any later call throws <see cref="ObjectDisposedException" />.</summary>
    public void Dispose()
    {
        CryptographicOperations.ZeroMemory(MemoryMarshal.AsBytes(encryptionRoundKeys.AsSpan()));
        CryptographicOperations.ZeroMemory(MemoryMarshal.AsBytes(decryptionRoundKeys.AsSpan()));
        disposed = true;
    }

    /// <summary>
    /// RFC 5794 section 2.4.2: SL1 (<paramref name="oddRound" /> <c>true</c>) or SL2, the
    /// bytes through SB1, SB2, SB3 and SB4 in turn, SL2 starting at SB3.
    /// </summary>
    internal static UInt128 Substitute(UInt128 value, bool oddRound)
    {
        Span<byte> bytes = stackalloc byte[BlockSize];
        try
        {
            BinaryPrimitives.WriteUInt128BigEndian(bytes, value);
            int firstBox = oddRound ? 0 : 2;
            for (int index = 0; index < BlockSize; index++)
            {
                bytes[index] = SubstitutionBoxes[(((index + firstBox) % 4) * 256) + bytes[index]];
            }

            return BinaryPrimitives.ReadUInt128BigEndian(bytes);
        }
        finally
        {
            CryptographicOperations.ZeroMemory(bytes);
        }
    }

    /// <summary>RFC 5794 section 2.4.3, the diffusion layer A, an involution.</summary>
    internal static UInt128 Diffuse(UInt128 value)
    {
        Span<byte> buffers = stackalloc byte[2 * BlockSize];
        Span<byte> input = buffers[..BlockSize];
        Span<byte> output = buffers[BlockSize..];
        try
        {
            BinaryPrimitives.WriteUInt128BigEndian(input, value);
            for (int index = 0; index < BlockSize; index++)
            {
                ReadOnlySpan<byte> taps = DiffusionInputs.Slice(index * 7, 7);
                output[index] = (byte)(input[taps[0]] ^ input[taps[1]] ^ input[taps[2]] ^ input[taps[3]] ^ input[taps[4]] ^ input[taps[5]] ^ input[taps[6]]);
            }

            return BinaryPrimitives.ReadUInt128BigEndian(output);
        }
        finally
        {
            CryptographicOperations.ZeroMemory(buffers);
        }
    }

    /// <summary>RFC 5794 section 2.4.1: FO (<paramref name="oddRound" /> <c>true</c>) or FE, A(SL(D ^ RK)).</summary>
    internal static UInt128 Round(UInt128 value, UInt128 roundKey, bool oddRound) => Diffuse(Substitute(value ^ roundKey, oddRound));

    /// <summary>
    /// RFC 5794 section 2.2: ek1 to ek{n+1}, each a word W XORed with the next word
    /// rotated, into <paramref name="roundKeys" />.
    /// </summary>
    private static void ExpandEncryptionRoundKeys(ReadOnlySpan<byte> key, Span<UInt128> roundKeys)
    {
        Span<UInt128> words = stackalloc UInt128[4];
        try
        {
            DeriveKeyWords(key, words);
            for (int index = 0; index < roundKeys.Length; index++)
            {
                int word = index % 4;
                roundKeys[index] = words[word] ^ UInt128.RotateRight(words[(word + 1) % 4], RoundKeyRotations[index / 4]);
            }
        }
        finally
        {
            CryptographicOperations.ZeroMemory(MemoryMarshal.AsBytes(words));
        }
    }

    /// <summary>
    /// RFC 5794 section 2.2: KL and KR from the key, then W0 to W3, the intermediate
    /// values of a three-round Feistel cipher keyed by the constants the key length
    /// selects, into <paramref name="words" />.
    /// </summary>
    private static void DeriveKeyWords(ReadOnlySpan<byte> key, Span<UInt128> words)
    {
        Span<byte> padded = stackalloc byte[2 * BlockSize];
        try
        {
            padded.Clear();
            key.CopyTo(padded);
            UInt128 keyRight = BinaryPrimitives.ReadUInt128BigEndian(padded[BlockSize..]);
            int firstConstant = (key.Length - 16) / 8;
            words[0] = BinaryPrimitives.ReadUInt128BigEndian(padded);
            words[1] = Round(words[0], Constants[firstConstant], oddRound: true) ^ keyRight;
            words[2] = Round(words[1], Constants[(firstConstant + 1) % 3], oddRound: false) ^ words[0];
            words[3] = Round(words[2], Constants[(firstConstant + 2) % 3], oddRound: true) ^ words[1];
        }
        finally
        {
            CryptographicOperations.ZeroMemory(padded);
        }
    }

    private static void RequireLength(int length, string parameterName)
    {
        if (length != BlockSize)
        {
            throw new ArgumentException($"ARIA needs {BlockSize} bytes here; this is {length}.", parameterName);
        }
    }

    /// <summary>
    /// RFC 5794 section 2.3: odd and even rounds alternating, then the last round's SL2
    /// and the extra key addition, with <paramref name="roundKeys" /> in the order this
    /// direction uses them.
    /// </summary>
    private static void TransformBlock(ReadOnlySpan<byte> source, Span<byte> destination, ReadOnlySpan<UInt128> roundKeys)
    {
        int rounds = roundKeys.Length - 1;
        UInt128 state = BinaryPrimitives.ReadUInt128BigEndian(source);
        for (int round = 0; round < rounds - 1; round++)
        {
            state = Round(state, roundKeys[round], oddRound: round % 2 == 0);
        }

        state = Substitute(state ^ roundKeys[rounds - 1], oddRound: false) ^ roundKeys[rounds];
        BinaryPrimitives.WriteUInt128BigEndian(destination, state);
    }

    private void RequireUsable(int sourceLength, int destinationLength)
    {
        ObjectDisposedException.ThrowIf(disposed, this);
        RequireLength(sourceLength, "source");
        RequireLength(destinationLength, "destination");
    }

using System.Text;
using Curl.Conformance.UnitProgram.Headers.AltSvc;
using Curl.Core.AltSvc;

namespace Curl.Conformance.UnitProgram.UnitTests.Headers.AltSvc;

[TestClass]
public sealed class AltSvcProgramsTests
{
    private const string Unit1654File =
        "h2 example.com 443 h3 shiny.example.com 8443 \"20191231 00:00:00\" 0 0\n"
        + "h2 expired.com 443 h3 shiny.example.com 8443 \"20190122 00:00:00\" 0 0\n"
        + "# a comment\n"
        + "h2 foo.example.com 443 h3 shiny.example.com 8443 \"20291231 23:30:00\" 0 0\n"
        + "  h1 example.com 443 h3 shiny.example.com 8443 \"20221231 00:00:01\" 0 0\n"
        + "\th3 example.com 443 h3 shiny.example.com 8443 \"20231231 00:00:00\" 0 0\n"
        + "    # also a comment\n"
        + "bad example.com 443 h3 shiny.example.com 8443 \"20191231 00:00:00\" 0 0\n"
        + "rubbish\n";

    private static readonly string[] Unit1654Out =
    [
        "# Your alt-svc cache. https://curl.se/docs/alt-svc.html",
        "# This file was generated by libcurl! Edit at your own risk.",
        "h2 example.com 443 h3 shiny.example.com 8443 \"20191231 00:00:00\" 0 0",
        "h2 foo.example.com 443 h3 shiny.example.com 8443 \"20291231 23:30:00\" 0 0",
        "h1 example.com 443 h3 shiny.example.com 8443 \"20221231 00:00:01\" 0 0",
        "h3 example.com 443 h3 shiny.example.com 8443 \"20231231 00:00:00\" 0 0",
        "h1 example.org 8080 h2 example.com 8080 \"20190125 22:34:21\" 0 0",
        "h1 2.example.org 8080 h3 2.example.org 8080 \"20190125 22:34:21\" 0 0",
        "h1 3.example.org 8080 h2 example.com 8080 \"20190125 22:34:21\" 0 0",
        "h1 3.example.org 8080 h3 yesyes.com 8080 \"20190125 22:34:21\" 0 0",
        "h2 example.org 80 h2 example.com 443 \"20190124 22:36:21\" 0 0",
        "h2 example.net 80 h2 example.net 443 \"20190124 22:37:21\" 0 0",
        "h2 test.se 443 h2 test2.se 443 \"20190124 22:37:21\" 0 0",
        "h2 test.se 443 h2 test3.se 443 \"20190124 22:36:21\" 0 0",
    ];

    private readonly List<string> folders = [];

    public TestContext TestContext { get; set; } = null!;

    [TestCleanup]
    public void DeleteTemporaryFolders()
    {
        foreach (string folder in folders)
        {
            Directory.Delete(folder, recursive: true);
        }
    }

    [TestMethod]
    public async Task RunAsync_Unit1654OnTheCasesFile_PassesAndSavesTheFileTheCaseVerifies()
    {
        string path = WriteTempFile(Unit1654File);
        using StringWriter standardError = new();

        UnitProgramResult result = await RunAsync("unit1654", path, standardError);

        Assert.AreEqual(string.Empty, standardError.ToString());
        Assert.AreEqual(0, result.ExitCode);
        Assert.AreEqual(string.Join(Environment.NewLine, Unit1654Out) + Environment.NewLine, await File.ReadAllTextAsync($"{path}-out", TestContext.CancellationToken));
    }

    [TestMethod]
    public async Task RunAsync_Unit1654WithoutTheFile_FailsTheCountChecksAndStillSaves()
    {
        string path = MissingPath();
        using StringWriter standardError = new();

        UnitProgramResult result = await RunAsync("unit1654", path, standardError);

        Assert.AreEqual(10, result.ExitCode);
        Assert.StartsWith("unit1654: wrong number of entries", standardError.ToString());
        Assert.IsTrue(File.Exists($"{path}-out"));
    }

    [TestMethod]
    public async Task RunAsync_Unit1654LookupFindsNothing_FailsOnceAndDoesNotSave()
    {
        string path = WriteTempFile(Unit1654File);
        using StringWriter standardError = new();
        Unit1654AltSvcParse program = new([], new CurlTimeClock(CurlTimeClock.UpstreamCaseEpochSeconds));

        UnitProgramResult result = await program.RunAsync(ContextFor(path, standardError), TestContext.CancellationToken);

        Assert.AreEqual(1, result.ExitCode);
        Assert.AreEqual("unit1654: alt-svc entry not found" + Environment.NewLine, standardError.ToString());
        Assert.IsFalse(File.Exists($"{path}-out"));
    }

    [TestMethod]
    public async Task RunAsync_Unit1654LookupFindsAnEntryWithoutMaPersistOrSameDestination_FailsEachCheck()
    {
        string path = WriteTempFile(Unit1654File);
        using StringWriter standardError = new();
        Unit1654AltSvcRow row = new(Unit1654AltSvcParse.LookupHost, Unit1654AltSvcParse.LookupPort, AltSvcAlpn.H1, "h2=\"other.example:443\"", null);
        Unit1654AltSvcParse program = new([row], new CurlTimeClock(CurlTimeClock.UpstreamCaseEpochSeconds));

        UnitProgramResult result = await program.RunAsync(ContextFor(path, standardError), TestContext.CancellationToken);

        Assert.AreEqual(3, result.ExitCode);
        Assert.AreEqual(
            string.Join(Environment.NewLine, "unit1654: unknown parameters hid ma", "unit1654: unknown parameters hid persist", "unit1654: wrong alt-svc destination") + Environment.NewLine,
            standardError.ToString());
    }

    [TestMethod]
    public async Task RunAsync_Unit1669OnFiveThousandAndTenLines_HoldsExactlyFiveThousand()
    {
        StringBuilder text = new();
        for (int line = 0; line < 5010; line++)
        {
            text.Append("h2 example.com 443 h3 shiny.example.com 8443 \"20191231 00:00:00\" 0 0\n");
        }

        string path = WriteTempFile(text.ToString());
        using StringWriter standardError = new();

        UnitProgramResult result = await RunAsync("unit1669", path, standardError);

        Assert.AreEqual(string.Empty, standardError.ToString());
        Assert.AreEqual(0, result.ExitCode);
    }

    [TestMethod]
    public async Task RunAsync_Unit1669WithoutTheFile_FailsTheCountCheck()
    {
        using StringWriter standardError = new();

        UnitProgramResult result = await RunAsync("unit1669", MissingPath(), standardError);

        Assert.AreEqual(1, result.ExitCode);
        Assert.AreEqual("unit1669: wrong number of entries" + Environment.NewLine, standardError.ToString());
    }

    [TestMethod]
    [DataRow("unit1654")]
    [DataRow("unit1669")]
    public async Task RunAsync_NoArgument_Throws(string programName)
    {
        IUnitProgram program = UnitPrograms.Ported.Find(programName)!;

        await Assert.ThrowsExactlyAsync<ArgumentException>(() => program.RunAsync(new UnitProgramContext(1654, []), TestContext.CancellationToken));
    }

    [TestMethod]
    [DataRow("unit1654")]
    [DataRow("unit1669")]
    public async Task RunAsync_NullContext_Throws(string programName)
    {
        IUnitProgram program = UnitPrograms.Ported.Find(programName)!;

        await Assert.ThrowsExactlyAsync<ArgumentNullException>(() => program.RunAsync(null!, TestContext.CancellationToken));
    }

    [TestMethod]
    public async Task LoadAsync_NullCache_Throws() =>
        await Assert.ThrowsExactlyAsync<ArgumentNullException>(() => AltSvcCacheFile.LoadAsync(null!, MissingPath(), TestContext.CancellationToken));

    [TestMethod]
    public void EpochSeconds_IsTheSecondTheClockAnswers()
    {
        CurlTimeClock clock = new(CurlTimeClock.UpstreamCaseEpochSeconds);

        Assert.AreEqual(1548369261, clock.EpochSeconds);
        Assert.AreEqual(new DateTimeOffset(2019, 1, 24, 22, 34, 21, TimeSpan.Zero), clock.GetUtcNow());
    }

    private static UnitProgramContext ContextFor(string path, TextWriter standardError) =>
        new(1654, [path]) { StandardError = standardError };

    private async Task<UnitProgramResult> RunAsync(string programName, string path, TextWriter standardError) =>
        await UnitPrograms.Ported.Find(programName)!.RunAsync(ContextFor(path, standardError), TestContext.CancellationToken);

    private string WriteTempFile(string text)
    {
        string path = MissingPath();
        File.WriteAllText(path, text);
        return path;
    }

    private string MissingPath()
    {
        string folder = Path.Combine(Path.GetTempPath(), $"altsvc-{Guid.NewGuid():N}");
        Directory.CreateDirectory(folder);
        folders.Add(folder);
        return Path.Combine(folder, "altsvc");
    }
}

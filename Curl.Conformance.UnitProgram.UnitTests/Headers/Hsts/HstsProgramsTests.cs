    public TestContext TestContext { get; set; } = null!;

    [TestMethod]
    public async Task RunAsync_Unit1660_WritesTheCasesOutputAndSavesTheCache()
    {
        string folder = CreateFolder();
        try
        {
            string file = Path.Combine(folder, "hsts1660");
            await File.WriteAllTextAsync(file, Unit1660File, TestContext.CancellationToken);
            using MemoryStream standardOutput = new();
            using StringWriter standardError = new();

            UnitProgramResult result = await UnitPrograms.Ported.Find("unit1660")!.RunAsync(new UnitProgramContext(1660, [file]) { StandardOutput = standardOutput, StandardError = standardError }, TestContext.CancellationToken);

            Assert.AreEqual(Unit1660Output, Encoding.Latin1.GetString(standardOutput.ToArray()));
            Assert.AreEqual(string.Empty, standardError.ToString());
            Assert.AreEqual(0, result.ExitCode);
            string newLine = Environment.NewLine;
            string expectedSave = $"# Your HSTS cache. https://curl.se/docs/hsts.html{newLine}# This file was generated by libcurl! Edit at your own risk.{newLine}"
                + $".new.example \"unlimited\"{newLine}.example.com \"20191001 04:47:41\"{newLine}example.org \"20200124 22:34:21\"{newLine}";
            Assert.AreEqual(expectedSave, await File.ReadAllTextAsync(file + ".save", TestContext.CancellationToken));
        }
        finally
        {
            Directory.Delete(folder, recursive: true);
        }
    }

    [TestMethod]
    [DataRow("max-age=\"1\"", false, "Curl_hsts_parse(max-age=\"1\") failed: 0\n")]
    [DataRow("max=\"1\"", true, "Curl_hsts_parse(max=\"1\") failed: 43\n")]
    public async Task RunAsync_Unit1660RowWhoseParseDiffers_WritesItToStandardErrorAndCountsAFailure(string header, bool accepted, string expectedError)
    {
        string folder = CreateFolder();
        try
        {
            string file = Path.Combine(folder, "hsts");
            await File.WriteAllTextAsync(file, string.Empty, TestContext.CancellationToken);
            using MemoryStream standardOutput = new();
            using StringWriter standardError = new();
            Unit1660Hsts program = new(Unit1660Hsts.UpstreamCurlTime, [("a.example", null, header, accepted)]);

            UnitProgramResult result = await program.RunAsync(new UnitProgramContext(1660, [file]) { StandardOutput = standardOutput, StandardError = standardError }, TestContext.CancellationToken);

            Assert.AreEqual(expectedError, standardError.ToString());
            Assert.AreEqual(1, result.ExitCode);
            Assert.StartsWith("Number of entries: ", Encoding.Latin1.GetString(standardOutput.ToArray()));
        }
        finally
        {
            Directory.Delete(folder, recursive: true);
        }
    }

    [TestMethod]
    [DataRow(Unit1674HstsEntryCap.UpstreamEntriesWritten, "OK\n", 0)]
    [DataRow(3, "Not OK: 3 entries\n", 1)]
    public async Task RunAsync_Unit1674_WritesOkOnlyWhenTheCacheHoldsMaxEntries(int entriesWritten, string expectedOutput, int expectedExitCode)
    {
        string folder = CreateFolder();
        try
        {
            using MemoryStream standardOutput = new();
            Unit1674HstsEntryCap program = new(Unit1660Hsts.UpstreamCurlTime, entriesWritten);

            UnitProgramResult result = await program.RunAsync(new UnitProgramContext(1674, [Path.Combine(folder, "hsts1674")]) { StandardOutput = standardOutput }, TestContext.CancellationToken);

            Assert.AreEqual(expectedOutput, Encoding.Latin1.GetString(standardOutput.ToArray()));
            Assert.AreEqual(expectedExitCode, result.ExitCode);
        }
        finally
        {
            Directory.Delete(folder, recursive: true);
        }
    }

    [TestMethod]
    public async Task RunAsync_Unit1674RegisteredPort_WritesOk()
    {
        string folder = CreateFolder();
        try
        {
            using MemoryStream standardOutput = new();

            UnitProgramResult result = await UnitPrograms.Ported.Find("unit1674")!.RunAsync(new UnitProgramContext(1674, [Path.Combine(folder, "hsts1674")]) { StandardOutput = standardOutput }, TestContext.CancellationToken);

            Assert.AreEqual("OK\n", Encoding.Latin1.GetString(standardOutput.ToArray()));
            Assert.AreEqual(0, result.ExitCode);
        }
        finally

            Directory.Delete(folder, recursive: true);
        }
    }

    [TestMethod]
    [DataRow("unit1660")]
    [DataRow("unit1674")]
    public async Task RunAsync_NullContext_Throws(string programName)
    {
        IUnitProgram program = UnitPrograms.Ported.Find(programName)!;

        await Assert.ThrowsExactlyAsync<ArgumentNullException>(() => program.RunAsync(null!, TestContext.CancellationToken));
    }

    [TestMethod]
    public void Constructor_Unit1660NullRows_Throws() =>
        Assert.ThrowsExactly<ArgumentNullException>(() => new Unit1660Hsts(0, null!));

    [TestMethod]
    public void Advance_CurlTimeClock_MovesOneSecondOn()
    {
        CurlTimeClock clock = new(100);

        clock.Advance();

        Assert.AreEqual(DateTimeOffset.FromUnixTimeSeconds(101), clock.GetUtcNow());
    }

    private static string CreateFolder() => Directory.CreateTempSubdirectory("curl-hsts-unit-").FullName;
}

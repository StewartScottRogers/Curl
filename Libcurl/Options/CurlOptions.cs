    private static readonly Dictionary<string, CurlEasyOption> RowsByName = Table.ToDictionary(row => row.Name, StringComparer.Ordinal);

    private static readonly Dictionary<CurlOption, CurlEasyOption> RowsById = Table.Where(row => !row.IsAlias).ToDictionary(row => row.Id);

    /// <summary>Every row of the table, in upstream's order.</summary>
    public static IReadOnlyList<CurlEasyOption> All => Table;

    /// <summary>
    /// <c>curl_easy_option_by_name</c>: the row named <paramref name="name"/> (without <c>CURLOPT_</c>),
    /// matched ignoring the case of ASCII letters only, as upstream's <c>curl_strequal</c> does; an
    /// alias name finds its own row.
    /// </summary>
    /// <param name="name">The option name to look up.</param>
    /// <returns>The row, or <see langword="null"/> when no row has the name.</returns>
    public static CurlEasyOption? ByName(string name) => RowsByName.GetValueOrDefault(AsciiUpper(name));

    /// <summary><c>curl_easy_option_by_id</c>: the row for <paramref name="id"/>, never an alias row.</summary>
    /// <param name="id">The option to look up.</param>
    /// <returns>The row, or <see langword="null"/> for a number no option has.</returns>
    public static CurlEasyOption? ById(CurlOption id) => RowsById.GetValueOrDefault(id);

    /// <summary><c>curl_easy_option_next</c>: the row after <paramref name="previous"/>, or the first row.</summary>
    /// <param name="previous">The row last returned, or <see langword="null"/> to start.</param>
    /// <returns>The next row, or <see langword="null"/> after the last row or for a row not in the table.</returns>
    public static CurlEasyOption? Next(CurlEasyOption? previous)
    {
        var next = previous is null ? 0 : Array.IndexOf(Table, previous) + 1;
        return next > 0 || previous is null ? Table.ElementAtOrDefault(next) : null;
    }

    private static string AsciiUpper(string name) =>
        string.Create(name.Length, name, static (span, source) =>
        {
            for (var i = 0; i < span.Length; i++)
            {
                span[i] = char.IsAsciiLetterLower(source[i]) ? (char)(source[i] - ('a' - 'A')) : source[i];
            }
        });

using Curl.Api.Options.Http;

namespace Curl.Api;

/// <summary>
/// The cookies a <see cref="CurlStores"/> keeps, as Netscape cookie-file lines (seven tab-separated
/// fields: domain, include subdomains, path, secure, expiry, name, value), the form
/// <c>CURLINFO_COOKIELIST</c> gives and <c>CURLOPT_COOKIELIST</c> takes. Each transfer starts with
/// exactly these cookies (<c>CURLOPT_COOKIELIST</c> <c>ALL</c>, then each line, with the cookie
/// engine on) and, when its handle is disposed, leaves the cookie list it ended with here.
/// Thread-safe.
/// </summary>
public sealed class CurlCookieStore
{
    private static readonly string[] FileHeader =
    [
        "# Netscape HTTP Cookie File",
        "# https://curl.se/docs/http-cookies.html",
        "# This file was generated by libcurl! Edit at your own risk.",
        string.Empty,
    ];

    private readonly Lock _gate = new();
    private List<string> _lines = [];

    internal CurlCookieStore()
    {
    }

    /// <summary>Every cookie, as Netscape cookie-file lines in the order they were added or reported.</summary>
    /// <returns>A copy of the lines.</returns>
    public IReadOnlyList<string> GetLines()
    {
        lock (_gate)
        {
            return [.. _lines];
        }
    }

    /// <summary>Adds one cookie; a transfer's own cookie engine replaces any cookie of the same domain, path and name.</summary>
    /// <param name="netscapeLine">The cookie as a Netscape cookie-file line (a <c>#HttpOnly_</c> domain prefix is kept).</param>
    /// <exception cref="ArgumentException"><paramref name="netscapeLine"/> is not seven tab-separated fields on one line.</exception>
    public void Add(string netscapeLine)
    {
        ArgumentNullException.ThrowIfNull(netscapeLine);
        if (netscapeLine.Split('\t').Length != 7 || netscapeLine.AsSpan().ContainsAny('\r', '\n'))
        {
            throw new ArgumentException("A cookie is one Netscape cookie-file line of seven tab-separated fields.", nameof(netscapeLine));
        }

        lock (_gate)
        {
            _lines.Add(netscapeLine);
        }
    }

    /// <summary>Removes every cookie: <c>CURLOPT_COOKIELIST</c> <c>ALL</c>.</summary>
    public void Clear() => ReplaceWith([]);

    /// <summary>Removes the session cookies, those whose expiry field is <c>0</c>: <c>CURLOPT_COOKIELIST</c> <c>SESS</c>.</summary>
    public void ClearSession()
    {
        lock (_gate)
        {
            _lines = [.. _lines.Where(line => line.Split('\t')[4] != "0")];
        }
    }

    /// <summary>Adds every cookie line of a Netscape cookie file, skipping comments and blank lines (a <c>#HttpOnly_</c> line is a cookie).</summary>
    /// <param name="path">The cookie file.</param>
    /// <param name="cancellationToken">Stops the read.</param>
    /// <returns>A task that completes when the cookies are added.</returns>
    /// <exception cref="ArgumentException">A line is not seven tab-separated fields; nothing is added.</exception>
    public async Task LoadAsync(string path, CancellationToken cancellationToken)
    {
        IReadOnlyList<string> lines = await StoreFile.ReadEntryLinesAsync(path, "#HttpOnly_", cancellationToken).ConfigureAwait(false);
        CurlCookieStore checkedLines = new();
        foreach (string line in lines)
        {
            checkedLines.Add(line);
        }

        lock (_gate)
        {
            _lines.AddRange(checkedLines._lines);
        }
    }

    /// <summary>Writes every cookie to a Netscape cookie file with curl's header, as <c>CURLOPT_COOKIEJAR</c> does.</summary>
    /// <param name="path">The cookie file, replaced if it exists.</param>
    /// <param name="cancellationToken">Stops the write.</param>
    /// <returns>A task that completes when the file is written.</returns>
    public Task SaveAsync(string path, CancellationToken cancellationToken) =>
        StoreFile.WriteAsync(path, FileHeader, GetLines(), cancellationToken);

    /// <summary>The HTTP options with the cookie engine on (an empty <c>CURLOPT_COOKIEFILE</c> when none is set) and <c>CURLOPT_COOKIELIST</c> <c>ALL</c> then every cookie.</summary>
    /// <param name="http">The handle's HTTP options.</param>
    /// <returns>The options the transfer starts with.</returns>
    internal EasyHttpOptions ApplyTo(EasyHttpOptions http) => http with
    {
        CookieFiles = http.CookieFiles.Count == 0 ? [string.Empty] : http.CookieFiles,
        CookieList = ["ALL", .. GetLines()],
    };

    /// <summary>Replaces every cookie with the list a transfer ended with (<c>CURLINFO_COOKIELIST</c>).</summary>
    /// <param name="lines">The Netscape cookie-file lines.</param>
    internal void ReplaceWith(IReadOnlyList<string> lines)
    {
        lock (_gate)
        {
            _lines = [.. lines];
        }
    }
}

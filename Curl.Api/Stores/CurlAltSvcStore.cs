using Curl.Api.Options.Http;

namespace Curl.Api;

/// <summary>
/// The alt-svc cache a <see cref="CurlStores"/> uses. libcurl keeps alt-svc only in a file
/// (<c>CURLOPT_ALTSVC</c>), so the store is that file: once <see cref="Use"/> names it, every
/// transfer reads and writes it with <see cref="Control"/> as <c>CURLOPT_ALTSVC_CTRL</c>, and the
/// store's other members read and write the same file. Until then, alt-svc stays as each handle
/// has it.
/// </summary>
public sealed class CurlAltSvcStore
{
    private static readonly string[] FileHeader =
    [
        "# Your alt-svc cache. https://curl.se/docs/alt-svc.html",
        "# This file was generated by libcurl! Edit at your own risk.",
    ];

    // One reference, so a reader never sees a path from one Use call with the control of another.
    private volatile Selection? _selection;

    internal CurlAltSvcStore()
    {
    }

    /// <summary>The cache file every transfer uses; <see langword="null"/> until <see cref="Use"/> names one.</summary>
    public string? FilePath => _selection?.Path;

    /// <summary>The <c>CURLOPT_ALTSVC_CTRL</c> bits every transfer uses; <see cref="AltSvcControl.None"/> until <see cref="Use"/>.</summary>
    public AltSvcControl Control => _selection?.Control ?? AltSvcControl.None;

    /// <summary>Makes <paramref name="path"/> the cache file of every later transfer, handled as <paramref name="control"/> says.</summary>
    /// <param name="path">The alt-svc cache file; it need not exist yet.</param>
    /// <param name="control">The <c>CURLALTSVC_*</c> bits: which HTTP versions are accepted, and whether the file is read only.</param>
    public void Use(string path, AltSvcControl control)
    {
        ArgumentException.ThrowIfNullOrEmpty(path);
        _selection = new Selection(path, control);
    }

    /// <summary>The entries in the cache file; none when it does not exist yet.</summary>
    /// <param name="cancellationToken">Stops the read.</param>
    /// <returns>The entries, in file order.</returns>
    /// <exception cref="InvalidOperationException"><see cref="Use"/> has named no file.</exception>
    public Task<IReadOnlyList<CurlAltSvcEntry>> GetEntriesAsync(CancellationToken cancellationToken) =>
        ReadEntriesAsync(RequiredPath(), cancellationToken);

    /// <summary>Adds an entry to the cache file, replacing any with the same origin protocol, host and port and alternative protocol.</summary>
    /// <param name="entry">The entry.</param>
    /// <param name="cancellationToken">Stops the read and write.</param>
    /// <returns>A task that completes when the file is written.</returns>
    /// <exception cref="InvalidOperationException"><see cref="Use"/> has named no file.</exception>
    public async Task AddAsync(CurlAltSvcEntry entry, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(entry);
        string path = RequiredPath();
        IReadOnlyList<CurlAltSvcEntry> entries = await ReadEntriesAsync(path, cancellationToken).ConfigureAwait(false);
        await WriteEntriesAsync(path, [.. entries.Where(existing => !SameAlternative(existing, entry)), entry], cancellationToken).ConfigureAwait(false);
    }

    /// <summary>Empties the cache file, leaving curl's header.</summary>
    /// <param name="cancellationToken">Stops the write.</param>
    /// <returns>A task that completes when the file is written.</returns>
    /// <exception cref="InvalidOperationException"><see cref="Use"/> has named no file.</exception>
    public Task ClearAsync(CancellationToken cancellationToken) => WriteEntriesAsync(RequiredPath(), [], cancellationToken);

    /// <summary>Replaces the cache file's entries with those of another alt-svc file.</summary>
    /// <param name="path">The alt-svc file to load.</param>
    /// <param name="cancellationToken">Stops the read and write.</param>
    /// <returns>A task that completes when the cache file is written.</returns>
    /// <exception cref="InvalidOperationException"><see cref="Use"/> has named no file.</exception>
    public async Task LoadAsync(string path, CancellationToken cancellationToken)
    {
        string cachePath = RequiredPath();
        IReadOnlyList<CurlAltSvcEntry> entries = await ReadEntriesAsync(path, cancellationToken).ConfigureAwait(false);
        await WriteEntriesAsync(cachePath, entries, cancellationToken).ConfigureAwait(false);
    }

    /// <summary>Writes the cache file's entries to another alt-svc file with curl's header.</summary>
    /// <param name="path">The file to write, replaced if it exists.</param>
    /// <param name="cancellationToken">Stops the read and write.</param>
    /// <returns>A task that completes when the file is written.</returns>
    /// <exception cref="InvalidOperationException"><see cref="Use"/> has named no file.</exception>
    public async Task SaveAsync(string path, CancellationToken cancellationToken)
    {
        IReadOnlyList<CurlAltSvcEntry> entries = await GetEntriesAsync(cancellationToken).ConfigureAwait(false);
        await WriteEntriesAsync(path, entries, cancellationToken).ConfigureAwait(false);
    }

    /// <summary>The HTTP options with the cache file and <see cref="Control"/> set, or unchanged until <see cref="Use"/>.</summary>
    /// <param name="http">The handle's HTTP options.</param>
    /// <returns>The options the transfer starts with.</returns>
    internal EasyHttpOptions ApplyTo(EasyHttpOptions http) =>
        _selection is { } selection ? http with { AltSvc = selection.Path, AltSvcControl = selection.Control } : http;

    /// <summary>The cache file path.</summary>
    /// <exception cref="InvalidOperationException"><see cref="Use"/> has named no file.</exception>
    private string RequiredPath() =>
        FilePath ?? throw new InvalidOperationException("No alt-svc cache file is in use; call Use first.");

    /// <summary>The entries of an alt-svc file, none when it does not exist; lines that are not entries are skipped.</summary>
    private static async Task<IReadOnlyList<CurlAltSvcEntry>> ReadEntriesAsync(string path, CancellationToken cancellationToken)
    {
        if (!File.Exists(path))
        {
            return [];
        }

        IReadOnlyList<string> lines = await StoreFile.ReadEntryLinesAsync(path, keptCommentPrefix: null, cancellationToken).ConfigureAwait(false);
        return [.. lines.Select(CurlAltSvcEntry.FromFileLine).OfType<CurlAltSvcEntry>()];
    }

    /// <summary>Writes entries to an alt-svc file under curl's header.</summary>
    private static Task WriteEntriesAsync(string path, IReadOnlyList<CurlAltSvcEntry> entries, CancellationToken cancellationToken) =>
        StoreFile.WriteAsync(path, FileHeader, entries.Select(entry => entry.ToFileLine()), cancellationToken);

    /// <summary>Whether two entries are for the same origin and alternative service (the origin host compared without case); expiry and the rest do not matter.</summary>
    private static bool SameAlternative(CurlAltSvcEntry left, CurlAltSvcEntry right) =>
        left.SourceAlpn == right.SourceAlpn
        && string.Equals(left.SourceHost, right.SourceHost, StringComparison.OrdinalIgnoreCase)
        && left.SourcePort == right.SourcePort
        && left.DestinationAlpn == right.DestinationAlpn;

    /// <summary>The file and control bits <see cref="Use"/> chose, held together so they change together.</summary>
    private sealed record Selection(string Path, AltSvcControl Control);
}

using Curl.Api.Callbacks;
using Curl.Api.Options.Http;

namespace Curl.Api;

/// <summary>
/// The HSTS entries a <see cref="CurlStores"/> keeps, one per host name. Each transfer has HSTS on
/// (<c>CURLHSTS_ENABLE</c>) and is preloaded with these entries through
/// <c>CURLOPT_HSTSREADFUNCTION</c>; when its handle is disposed, <c>CURLOPT_HSTSWRITEFUNCTION</c>
/// leaves the cache it ended with here. Thread-safe.
/// </summary>
public sealed class CurlHstsStore
{
    private const string UnlimitedText = "unlimited";

    private static readonly string[] FileHeader =
    [
        "# Your HSTS cache. https://curl.se/docs/hsts.html",
        "# This file was generated by libcurl! Edit at your own risk.",
    ];

    private readonly Lock _gate = new();
    private List<HstsEntry> _entries = [];

    internal CurlHstsStore()
    {
    }

    /// <summary>Every entry, in the order they were added or saved by a transfer.</summary>
    /// <returns>A copy of the entries.</returns>
    public IReadOnlyList<HstsEntry> GetEntries()
    {
        lock (_gate)
        {
            return [.. _entries];
        }
    }

    /// <summary>Adds an entry, replacing any entry for the same host name (compared without case).</summary>
    /// <param name="entry">The entry; <see cref="HstsEntry.Expire"/> is <c>YYYYMMDD HH:MM:SS</c>, or <see langword="null"/> for one that never expires.</param>
    /// <exception cref="ArgumentException">The entry's name is empty.</exception>
    public void Add(HstsEntry entry)
    {
        ArgumentNullException.ThrowIfNull(entry);
        ArgumentException.ThrowIfNullOrEmpty(entry.Name, nameof(entry));
        lock (_gate)
        {
            _entries.RemoveAll(existing => string.Equals(existing.Name, entry.Name, StringComparison.OrdinalIgnoreCase));
            _entries.Add(entry);
        }
    }

    /// <summary>Removes every entry.</summary>
    public void Clear() => ReplaceWith([]);

    /// <summary>
    /// Adds every entry of an HSTS cache file (<c>[.]host "YYYYMMDD HH:MM:SS"</c>, a leading dot for
    /// subdomains, <c>unlimited</c> for no expiry), skipping comments, blank lines and lines without
    /// a quoted expiry, as curl does.
    /// </summary>
    /// <param name="path">The HSTS cache file.</param>
    /// <param name="cancellationToken">Stops the read.</param>
    /// <returns>A task that completes when the entries are added.</returns>
    public async Task LoadAsync(string path, CancellationToken cancellationToken)
    {
        IReadOnlyList<string> lines = await StoreFile.ReadEntryLinesAsync(path, keptCommentPrefix: null, cancellationToken).ConfigureAwait(false);
        foreach (HstsEntry? entry in lines.Select(EntryOf))
        {
            if (entry is not null)
            {
                Add(entry);
            }
        }
    }

    /// <summary>Writes every entry to an HSTS cache file with curl's header, as <c>CURLOPT_HSTS</c> does.</summary>
    /// <param name="path">The HSTS cache file, replaced if it exists.</param>
    /// <param name="cancellationToken">Stops the write.</param>
    /// <returns>A task that completes when the file is written.</returns>
    public Task SaveAsync(string path, CancellationToken cancellationToken) =>
        StoreFile.WriteAsync(path, FileHeader, GetEntries().Select(LineOf), cancellationToken);

    /// <summary>The HTTP options with HSTS on (<c>CURLHSTS_ENABLE</c> added to <c>CURLOPT_HSTS_CTRL</c>).</summary>
    /// <param name="http">The handle's HTTP options.</param>
    /// <returns>The options the transfer starts with.</returns>
    internal static EasyHttpOptions ApplyTo(EasyHttpOptions http) =>
        http with { HstsControl = http.HstsControl | HstsControl.Enable };

    /// <summary>The callback options with <see cref="CreateReadCallback"/> and <see cref="CreateWriteCallback"/> set.</summary>
    /// <param name="callbacks">The handle's callback options.</param>
    /// <returns>The options the transfer starts with.</returns>
    internal EasyCallbackOptions ApplyTo(EasyCallbackOptions callbacks) =>
        callbacks with { HstsRead = CreateReadCallback(), HstsWrite = CreateWriteCallback() };

    /// <summary>A <c>CURLOPT_HSTSREADFUNCTION</c> that hands over the entries as they are now, one per call, then answers <see cref="HstsResult.Done"/>.</summary>
    /// <returns>The read callback.</returns>
    internal HstsReadCallback CreateReadCallback()
    {
        IReadOnlyList<HstsEntry> entries = GetEntries();
        int next = 0;
        return (out HstsEntry? entry) =>
        {
            entry = next < entries.Count ? entries[next++] : null;
            return entry is null ? HstsResult.Done : HstsResult.Ok;
        };
    }

    /// <summary>
    /// A <c>CURLOPT_HSTSWRITEFUNCTION</c> that collects the cache it is handed and, at its last
    /// entry, replaces the store's entries with it; it always answers <see cref="HstsResult.Ok"/>.
    /// </summary>
    /// <returns>The write callback.</returns>
    internal HstsWriteCallback CreateWriteCallback()
    {
        List<HstsEntry> saved = [];
        return (entry, index, total) =>
        {
            if (index == 0)
            {
                saved.Clear();
            }

            saved.Add(entry);
            if (index == total - 1)
            {
                ReplaceWith(saved);
            }

            return HstsResult.Ok;
        };
    }

    private void ReplaceWith(IReadOnlyList<HstsEntry> entries)
    {
        lock (_gate)
        {
            _entries = [.. entries];
        }
    }

    private static string LineOf(HstsEntry entry) =>
        $"{(entry.IncludeSubDomains ? "." : string.Empty)}{entry.Name} \"{entry.Expire ?? UnlimitedText}\"";

    private static HstsEntry? EntryOf(string line)
    {
        string[] parts = line.Trim().Split(' ', 2);
        if (parts.Length != 2 || UnquotedOf(parts[1]) is not { } expiry)
        {
            return null;
        }

        bool includeSubDomains = parts[0].StartsWith('.');
        return new HstsEntry(parts[0][(includeSubDomains ? 1 : 0)..], includeSubDomains, expiry == UnlimitedText ? null : expiry);
    }

    private static string? UnquotedOf(string text) =>
        text.Length >= 2 && text[0] == '"' && text[^1] == '"' ? text[1..^1] : null;
}

#!/usr/bin/env bash
# Linux and macOS twin of Set-DifferentialEnvironment.ps1 (it also runs in Git Bash and MSYS2 on Windows).
#
# SYNOPSIS
# Sets the CURL_DIFFERENTIAL_* variables the differential tests read, for the calling shell, with no interaction.
#
# DESCRIPTION
# SOURCE it so the variables stay set in your shell: ". ./Set-DifferentialEnvironment.sh".
# Running it ("./Set-DifferentialEnvironment.sh") would set them in a child process that ends at once, so
# it refuses with a message and changes nothing. Every error below is reported on stderr and the script
# RETURNS (it never calls exit, which would close your shell) with status 1, leaving the four variables as
# they were. It sets no shell option and leaves no variable or function behind but the four below.
# Sets, for the current shell only:
#
#   CURL_DIFFERENTIAL_REFERENCE          the reference curl (curl 8.22.0; the Schannel build on Windows, the OpenSSL build elsewhere)
#   CURL_DIFFERENTIAL_REFERENCE_LIBRARY  the reference libcurl (libcurl.so.4, libcurl.4.dylib or libcurl-4.dll), found beside or near that curl
#   CURL_DIFFERENTIAL_REFERENCE_LIBCURL  the same library (the libcurl scenario tests read this name)
#   CURL_DIFFERENTIAL_PKI                the directory New-DifferentialPki wrote
#
# Without --reference-curl it looks for a curl whose "curl -V" reports "curl 8.22.0" and "OpenSSL" ("Schannel"
# in Git Bash, MSYS2 and Cygwin): first every curl on PATH, then the Homebrew, /usr/local and (on Windows)
# "ucrt64/bin" and "mingw64/bin" folders. When none is found it stops with an error naming what it looked
# for. It downloads nothing. Paths are printed absolute, with forward slashes.
#
# OPTIONS
#   --reference-curl <path>      Path of the reference curl; skips the search. Still must exist.
#   --reference-library <path>   Path of the reference libcurl; default is the libcurl beside the reference
#                                curl, in its ../lib, ../lib64 or ../lib/<triplet> folder, or in a system folder.
#   --pki <directory>            An existing directory of differential certificates; default is
#                                "$XDG_DATA_HOME/Curl/differential-pki" ("$HOME/.local/share/..." when unset;
#                                "$HOME/Library/Application Support/Curl/differential-pki" on macOS;
#                                "%LOCALAPPDATA%/Curl/differential-pki" on Windows), generated by
#                                New-DifferentialPki.sh beside this script when it holds no ca.pem.
#   -h, --help                   Print this help (the lines of this header) and return.
#
# EXAMPLE
#   . ./Set-DifferentialEnvironment.sh
#   . ./Set-DifferentialEnvironment.sh --reference-curl /opt/curl-8.22.0/bin/curl

# Refuse politely when executed: a child process cannot set variables in the shell that started it.
# "return" only works in a sourced file, so the executed case, which has nothing to protect, uses exit.
if [ "${BASH_SOURCE[0]:-}" = "$0" ]; then
    echo "Set-DifferentialEnvironment.sh sets variables for your shell, so source it instead: . ./Set-DifferentialEnvironment.sh" >&2
    exit 1
fi

_cde_script="${BASH_SOURCE[0]}"

_cde_fail() { echo "Set-DifferentialEnvironment.sh: $*" >&2; }

# Prints the OS family: windows (Git Bash, MSYS2, Cygwin), macos or linux.
_cde_os() {
    case "$(uname -s 2>/dev/null)" in
        MINGW*|MSYS*|CYGWIN*) echo windows ;;
        Darwin) echo macos ;;
        *) echo linux ;;
    esac
}

# Prints the absolute path of an existing file or directory with forward slashes (no symlink following of a file's own name).
_cde_resolve() {
    local path="$1" dir base
    if [ -d "$path" ]; then dir="$path"; base=""; else dir="$(dirname "$path")"; base="/$(basename "$path")"; fi
    dir="$(cd "$dir" 2>/dev/null && pwd -P)" || return 1
    if command -v cygpath >/dev/null 2>&1; then dir="$(cygpath -m "$dir")"; fi
    [ "$dir" = "/" ] && dir=""
    echo "$dir$base"
}

# Succeeds when the file is a curl whose "-V" report holds the wanted version and TLS backend.
_cde_is_reference_curl() {
    local path="$1" report
    [ -f "$path" ] || return 1
    report="$("$path" -V 2>&1)" || true
    case "$report" in *"$_cde_wanted_version"*) ;; *) return 1 ;; esac
    case "$report" in *"$_cde_wanted_tls"*) return 0 ;; *) return 1 ;; esac
}

# Prints, one per line, the folders to look for a reference curl in: PATH first, then the well-known ones.
_cde_candidate_folders() {
    local rest="${PATH:-}" entry root tool found folder
    while [ -n "$rest" ]; do
        entry="${rest%%:*}"
        if [ "$entry" = "$rest" ]; then rest=""; else rest="${rest#*:}"; fi
        [ -n "$entry" ] && echo "$entry"
    done
    echo /opt/homebrew/opt/curl/bin
    echo /usr/local/opt/curl/bin
    echo /usr/local/bin
    echo /usr/bin
    if [ "$(_cde_os)" = windows ]; then
        for tool in bash pacman; do
            found="$(command -v "$tool" 2>/dev/null)" || continue
            folder="$(dirname "$found")"
            for root in "$(dirname "$folder")" "$(dirname "$(dirname "$folder")")"; do
                echo "$root/ucrt64/bin"
                echo "$root/mingw64/bin"
            done
        done
    fi
}

# Prints the first existing libcurl beside or near the given curl, or nothing.
_cde_find_library() {
    local bin_folder root candidate name
    bin_folder="$(dirname "$1")"
    root="$(dirname "$bin_folder")"
    for name in libcurl-4.dll libcurl.4.dylib libcurl.so.4 libcurl.dylib libcurl.so; do
        for candidate in "$bin_folder/$name" "$root/lib/$name" "$root/lib64/$name" "$root"/lib/*-linux-gnu*/"$name" \
                         "/usr/lib/$name" "/usr/lib64/$name" /usr/lib/*-linux-gnu*/"$name" "/usr/local/lib/$name"; do
            if [ -f "$candidate" ]; then echo "$candidate"; return 0; fi
        done
    done
    return 1
}

# Prints the default differential PKI folder for this operating system.
_cde_default_pki() {
    case "$(_cde_os)" in
        windows) echo "${LOCALAPPDATA:-$HOME/AppData/Local}/Curl/differential-pki" | tr '\\' '/' ;;
        macos) echo "$HOME/Library/Application Support/Curl/differential-pki" ;;
        *) echo "${XDG_DATA_HOME:-$HOME/.local/share}/Curl/differential-pki" ;;
    esac
}

_cde_main() {
    local reference_curl="" reference_library="" pki="" searched="" folder candidate script_dir name
    _cde_wanted_version='curl 8.22.0'
    if [ "$(_cde_os)" = windows ]; then _cde_wanted_tls='Schannel'; else _cde_wanted_tls='OpenSSL'; fi

    while [ $# -gt 0 ]; do
        case "$1" in
            -h|--help) sed -n '2,/^$/p' "$_cde_script" | sed 's/^# \{0,1\}//'; return 0 ;;
            --reference-curl|--reference-library|--pki)
                if [ $# -lt 2 ]; then _cde_fail "$1 needs a value."; return 1; fi
                case "$1" in
                    --reference-curl) reference_curl="$2" ;;
                    --reference-library) reference_library="$2" ;;
                    --pki) pki="$2" ;;
                esac
                shift 2 ;;
            *) _cde_fail "unknown option '$1'. Use --reference-curl, --reference-library or --pki."; return 1 ;;
        esac
    done

    if [ -z "$reference_curl" ]; then
        while IFS= read -r folder; do
            for name in curl.exe curl; do
                candidate="$folder/$name"
                case "$searched" in *"
$candidate
"*) continue ;; esac
                searched="$searched
$candidate
"
                if _cde_is_reference_curl "$candidate"; then reference_curl="$candidate"; break 2; fi
            done
        done <<EOF
$(_cde_candidate_folders)
EOF
        if [ -z "$reference_curl" ]; then
            _cde_fail "No curl reporting '$_cde_wanted_version' and '$_cde_wanted_tls' in 'curl -V' was found. Looked in: the PATH folders, then the Homebrew, /usr/local, /usr/bin and (on Windows) ucrt64/bin and mingw64/bin folders. Point at one with --reference-curl <path to curl> (and --reference-library <path to libcurl>)."
            return 1
        fi
    elif [ ! -f "$reference_curl" ]; then
        _cde_fail "No curl reporting '$_cde_wanted_version' and '$_cde_wanted_tls' in 'curl -V' was found: --reference-curl '$reference_curl' does not exist. Point --reference-curl at the reference curl."
        return 1
    fi
    reference_curl="$(_cde_resolve "$reference_curl")" || { _cde_fail "cannot resolve '$reference_curl'."; return 1; }

    if [ -z "$reference_library" ]; then reference_library="$(_cde_find_library "$reference_curl")"; fi
    if [ -z "$reference_library" ] || [ ! -f "$reference_library" ]; then
        _cde_fail "The reference libcurl '${reference_library:-libcurl beside $reference_curl}' does not exist. Point --reference-library at the libcurl that belongs to the reference curl."
        return 1
    fi
    reference_library="$(_cde_resolve "$reference_library")" || { _cde_fail "cannot resolve '$reference_library'."; return 1; }

    if [ -z "$pki" ]; then
        pki="$(_cde_default_pki)"
        if [ ! -e "$pki/ca.pem" ]; then
            script_dir="$(cd "$(dirname "$_cde_script")" && pwd)"
            if [ ! -f "$script_dir/New-DifferentialPki.sh" ]; then
                _cde_fail "'$pki' holds no ca.pem and '$script_dir/New-DifferentialPki.sh' does not exist to generate it. Run New-DifferentialPki.ps1 -Directory '$pki' with PowerShell, or point --pki at an existing directory."
                return 1
            fi
            bash "$script_dir/New-DifferentialPki.sh" --directory "$pki" || { _cde_fail "New-DifferentialPki.sh failed."; return 1; }
        fi
    elif [ ! -d "$pki" ]; then
        _cde_fail "The --pki directory '$pki' does not exist."
        return 1
    fi
    pki="$(_cde_resolve "$pki")" || { _cde_fail "cannot resolve '$pki'."; return 1; }

    export CURL_DIFFERENTIAL_REFERENCE="$reference_curl"
    export CURL_DIFFERENTIAL_REFERENCE_LIBRARY="$reference_library"
    export CURL_DIFFERENTIAL_REFERENCE_LIBCURL="$reference_library"
    export CURL_DIFFERENTIAL_PKI="$pki"
    echo "CURL_DIFFERENTIAL_REFERENCE=$reference_curl"
    echo "CURL_DIFFERENTIAL_REFERENCE_LIBRARY=$reference_library"
    echo "CURL_DIFFERENTIAL_REFERENCE_LIBCURL=$reference_library"
    echo "CURL_DIFFERENTIAL_PKI=$pki"
}

# Removes everything this script defined except the four exported variables.
_cde_cleanup() {
    unset -f _cde_fail _cde_os _cde_resolve _cde_is_reference_curl _cde_candidate_folders _cde_find_library _cde_default_pki _cde_main _cde_cleanup
    unset _cde_wanted_version _cde_wanted_tls _cde_script
}

if _cde_main "$@"; then _cde_cleanup; return 0; else _cde_cleanup; return 1; fi

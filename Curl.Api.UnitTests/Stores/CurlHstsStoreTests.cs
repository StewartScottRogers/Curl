using Curl.Api.Callbacks;
using Curl.Api.Options.Http;

namespace Curl.Api.Stores;

[TestClass]
public sealed class CurlHstsStoreTests
{
    private static readonly HstsEntry Example = new("example.com", IncludeSubDomains: true, "20271231 00:00:00");
    private static readonly HstsEntry Forever = new("forever.example", IncludeSubDomains: false, Expire: null);

    private DirectoryInfo _directory = null!;

    public TestContext TestContext { get; set; } = null!;

    [TestInitialize]
    public void CreateDirectory() => _directory = Directory.CreateTempSubdirectory("curl-api-hsts-");

    [TestCleanup]
    public void DeleteDirectory() => _directory.Delete(recursive: true);

    [TestMethod]
    public void Add_ListsTheEntriesInOrder()
    {
        CurlHstsStore store = new();

        store.Add(Example);
        store.Add(Forever);

        CollectionAssert.AreEqual(new[] { Example, Forever }, store.GetEntries().ToArray());
    }

    [TestMethod]
    public void Add_SameHostInAnotherCase_ReplacesTheEntry()
    {
        CurlHstsStore store = new();
        store.Add(Example);
        store.Add(Forever);
        HstsEntry replacement = new("EXAMPLE.com", IncludeSubDomains: false, "20300101 00:00:00");

        store.Add(replacement);

        CollectionAssert.AreEqual(new[] { Forever, replacement }, store.GetEntries().ToArray());
    }

    [TestMethod]
    public void Add_EmptyName_Throws()
    {
        Assert.ThrowsExactly<ArgumentException>(() => new CurlHstsStore().Add(new HstsEntry(string.Empty, false, null)));
    }

    [TestMethod]
    public void Add_Null_Throws()
    {
        Assert.ThrowsExactly<ArgumentNullException>(() => new CurlHstsStore().Add(null!));
    }

    [TestMethod]
    public void Clear_RemovesEveryEntry()
    {
        CurlHstsStore store = new();
        store.Add(Example);

        store.Clear();

        Assert.IsEmpty(store.GetEntries());
    }

    [TestMethod]
    public async Task SaveAsync_WritesCurlsHeaderThenOneLinePerEntry()
    {
        string path = Path.Combine(_directory.FullName, "hsts.txt");
        CurlHstsStore store = new();
        store.Add(Example);
        store.Add(Forever);

        await store.SaveAsync(path, TestContext.CancellationToken);

        string expected =
            "# Your HSTS cache. https://curl.se/docs/hsts.html\n# This file was generated by libcurl! Edit at your own risk.\n"
            + ".example.com \"20271231 00:00:00\"\nforever.example \"unlimited\"\n";
        Assert.AreEqual(expected, await File.ReadAllTextAsync(path, TestContext.CancellationToken));
    }

    [TestMethod]
    public async Task LoadAsync_AddsEveryWellFormedEntryAndSkipsTheRest()
    {
        string path = Path.Combine(_directory.FullName, "hsts.txt");
        string text =
            "# comment\n\n.example.com \"20271231 00:00:00\"\nforever.example \"unlimited\"\n"
            + "nospace\nshort \"\nunquoted 20271231\nopen \"20271231\n";
        await File.WriteAllTextAsync(path, text, TestContext.CancellationToken);
        CurlHstsStore store = new();

        await store.LoadAsync(path, TestContext.CancellationToken);

        CollectionAssert.AreEqual(new[] { Example, Forever }, store.GetEntries().ToArray());
    }

    [TestMethod]
    public void ApplyTo_Http_AddsEnableToTheControlBits()
    {
        EasyHttpOptions http = CurlHstsStore.ApplyTo(new EasyHttpOptions { HstsControl = HstsControl.ReadOnlyFile });

        Assert.AreEqual(HstsControl.Enable | HstsControl.ReadOnlyFile, http.HstsControl);
    }

    [TestMethod]
    public void ApplyTo_Callbacks_SetsTheReadAndWriteCallbacks()
    {
        CurlHstsStore store = new();
        store.Add(Forever);
        EasyCallbackOptions callbacks = store.ApplyTo(new EasyCallbackOptions());

        Assert.AreEqual(HstsResult.Ok, callbacks.HstsRead!(out HstsEntry? read));
        Assert.AreEqual(Forever, read);
        Assert.AreEqual(HstsResult.Done, callbacks.HstsRead!(out HstsEntry? done));
        Assert.IsNull(done);
        Assert.AreEqual(HstsResult.Ok, callbacks.HstsWrite!(Example, 0, 1));
        CollectionAssert.AreEqual(new[] { Example }, store.GetEntries().ToArray());
    }

    [TestMethod]
    public void ReadCallback_HandsOverTheEntriesAsTheyWereThenDone()
    {
        CurlHstsStore store = new();
        store.Add(Example);
        store.Add(Forever);
        HstsReadCallback read = store.CreateReadCallback();
        store.Clear();

        Assert.AreEqual(HstsResult.Ok, read(out HstsEntry? first));
        Assert.AreEqual(HstsResult.Ok, read(out HstsEntry? second));
        Assert.AreEqual(HstsResult.Done, read(out HstsEntry? third));
        Assert.AreEqual(Example, first);
        Assert.AreEqual(Forever, second);
        Assert.IsNull(third);
    }

    [TestMethod]
    public void WriteCallback_ReplacesTheEntriesAtTheLastOne()
    {
        CurlHstsStore store = new();
        store.Add(Forever);
        HstsWriteCallback write = store.CreateWriteCallback();

        Assert.AreEqual(HstsResult.Ok, write(Example, 0, 2));
        CollectionAssert.AreEqual(new[] { Forever }, store.GetEntries().ToArray());
        Assert.AreEqual(HstsResult.Ok, write(Forever, 1, 2));

        CollectionAssert.AreEqual(new[] { Example, Forever }, store.GetEntries().ToArray());
    }

    [TestMethod]
    public void WriteCallback_SecondSave_StartsAFreshCollection()
    {
        CurlHstsStore store = new();
        HstsWriteCallback write = store.CreateWriteCallback();
        write(Example, 0, 1);

        write(Forever, 0, 1);

        CollectionAssert.AreEqual(new[] { Forever }, store.GetEntries().ToArray());
    }
}

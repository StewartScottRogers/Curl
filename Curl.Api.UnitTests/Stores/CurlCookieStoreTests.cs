using Curl.Api.Options.Http;

namespace Curl.Api.Stores;

[TestClass]
public sealed class CurlCookieStoreTests
{
    private const string Persistent = "example.com\tFALSE\t/\tFALSE\t1924992000\tid\t42";
    private const string Session = "example.com\tFALSE\t/\tFALSE\t0\tsid\tabc";
    private const string HttpOnly = "#HttpOnly_example.org\tTRUE\t/\tTRUE\t1924992000\ttoken\tx";

    private DirectoryInfo _directory = null!;

    [TestInitialize]
    public void CreateDirectory() => _directory = Directory.CreateTempSubdirectory("curl-api-cookies-");

    [TestCleanup]
    public void DeleteDirectory() => _directory.Delete(recursive: true);

    [TestMethod]
    public void NewStore_HasNoCookies()
    {
        Assert.IsEmpty(new CurlCookieStore().GetLines());
    }

    [TestMethod]
    public void Add_ListsTheCookiesInOrder()
    {
        CurlCookieStore store = new();

        store.Add(Persistent);
        store.Add(HttpOnly);

        CollectionAssert.AreEqual(new[] { Persistent, HttpOnly }, store.GetLines().ToArray());
    }

    [TestMethod]
    public void GetLines_ReturnsACopy()
    {
        CurlCookieStore store = new();
        IReadOnlyList<string> before = store.GetLines();

        store.Add(Persistent);

        Assert.IsEmpty(before);
    }

    [TestMethod]
    [DataRow("name=value")]
    [DataRow("a\tb\tc\td\te\tf")]
    [DataRow("a\tb\tc\td\te\tf\tg\th")]
    [DataRow("a\tb\tc\td\te\tf\tg\nh")]
    [DataRow("a\tb\tc\td\te\tf\tg\r")]
    public void Add_NotOneNetscapeLine_Throws(string line)
    {
        CurlCookieStore store = new();

        Assert.ThrowsExactly<ArgumentException>(() => store.Add(line));
        Assert.IsEmpty(store.GetLines());
    }

    [TestMethod]
    public void Add_Null_Throws()
    {
        Assert.ThrowsExactly<ArgumentNullException>(() => new CurlCookieStore().Add(null!));
    }

    [TestMethod]
    public void Clear_RemovesEveryCookie()
    {
        CurlCookieStore store = new();
        store.Add(Persistent);
        store.Add(Session);

        store.Clear();

        Assert.IsEmpty(store.GetLines());
    }

    [TestMethod]
    public void ClearSession_RemovesOnlyCookiesWithExpiryZero()
    {
        CurlCookieStore store = new();
        store.Add(Persistent);
        store.Add(Session);
        store.Add(HttpOnly);

        store.ClearSession();

        CollectionAssert.AreEqual(new[] { Persistent, HttpOnly }, store.GetLines().ToArray());
    }

    [TestMethod]
    public async Task LoadAsync_AddsCookieLinesAndSkipsCommentsAndBlankLines()
    {
        string path = Path.Combine(_directory.FullName, "cookies.txt");
        await File.WriteAllTextAsync(path, $"# Netscape HTTP Cookie File\n\n   \n{Persistent}\n{HttpOnly}\n# {Session}\n", TestContext.CancellationToken);
        CurlCookieStore store = new();
        store.Add(Session);

        await store.LoadAsync(path, TestContext.CancellationToken);

        CollectionAssert.AreEqual(new[] { Session, Persistent, HttpOnly }, store.GetLines().ToArray());
    }

    [TestMethod]
    public async Task LoadAsync_MalformedLine_ThrowsAndAddsNothing()
    {
        string path = Path.Combine(_directory.FullName, "cookies.txt");
        await File.WriteAllTextAsync(path, $"{Persistent}\nnot a cookie\n", TestContext.CancellationToken);
        CurlCookieStore store = new();

        await Assert.ThrowsExactlyAsync<ArgumentException>(() => store.LoadAsync(path, TestContext.CancellationToken));

        Assert.IsEmpty(store.GetLines());
    }

    [TestMethod]
    public async Task LoadAsync_EmptyPath_Throws()
    {
        await Assert.ThrowsExactlyAsync<ArgumentException>(() => new CurlCookieStore().LoadAsync(string.Empty, TestContext.CancellationToken));
    }

    [TestMethod]
    public async Task SaveAsync_WritesCurlsHeaderThenEveryCookie()
    {
        string path = Path.Combine(_directory.FullName, "jar.txt");
        CurlCookieStore store = new();
        store.Add(Persistent);
        store.Add(HttpOnly);

        await store.SaveAsync(path, TestContext.CancellationToken);

        string expected =
            "# Netscape HTTP Cookie File\n# https://curl.se/docs/http-cookies.html\n# This file was generated by libcurl! Edit at your own risk.\n\n"
            + Persistent + "\n" + HttpOnly + "\n";
        Assert.AreEqual(expected, await File.ReadAllTextAsync(path, TestContext.CancellationToken));
    }

    [TestMethod]
    public async Task SaveAsync_ThenLoadAsync_RoundTrips()
    {
        string path = Path.Combine(_directory.FullName, "jar.txt");
        CurlCookieStore saved = new();
        saved.Add(Persistent);
        saved.Add(HttpOnly);
        CurlCookieStore loaded = new();

        await saved.SaveAsync(path, TestContext.CancellationToken);
        await loaded.LoadAsync(path, TestContext.CancellationToken);

        CollectionAssert.AreEqual(saved.GetLines().ToArray(), loaded.GetLines().ToArray());
    }

    [TestMethod]
    public void ApplyTo_NoCookieFile_TurnsTheEngineOnAndListsAllThenEveryCookie()
    {
        CurlCookieStore store = new();
        store.Add(Persistent);

        EasyHttpOptions http = store.ApplyTo(new EasyHttpOptions());

        CollectionAssert.AreEqual(new[] { string.Empty }, http.CookieFiles.ToArray());
        CollectionAssert.AreEqual(new[] { "ALL", Persistent }, http.CookieList.ToArray());
    }

    [TestMethod]
    public void ApplyTo_KeepsCookieFilesAlreadySet()
    {
        EasyHttpOptions http = new CurlCookieStore().ApplyTo(new EasyHttpOptions { CookieFiles = ["in.txt"] });

        CollectionAssert.AreEqual(new[] { "in.txt" }, http.CookieFiles.ToArray());
        CollectionAssert.AreEqual(new[] { "ALL" }, http.CookieList.ToArray());
    }

    [TestMethod]
    public void ReplaceWith_ReplacesEveryCookie()
    {
        CurlCookieStore store = new();
        store.Add(Persistent);

        store.ReplaceWith([Session]);

        CollectionAssert.AreEqual(new[] { Session }, store.GetLines().ToArray());
    }

    public TestContext TestContext { get; set; } = null!;
}

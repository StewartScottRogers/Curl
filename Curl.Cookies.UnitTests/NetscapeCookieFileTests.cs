        Assert.AreEqual(
            "A20=20; __Host-A9=9; A18=1 8 ; A17=17; A7=7; A6=6; A5=5; A4=4; A2=2; A1=1; =14",
            store.GetCookieHeader(new Uri("http://127.0.0.1:18221/p/x"), secure: false, Now));
    }


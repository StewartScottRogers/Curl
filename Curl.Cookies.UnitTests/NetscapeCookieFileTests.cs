            + "127.0.0.1\tFALSE\tnoslash\tFALSE\t0\tA7\t7\n"
            + "127.0.0.1\tFALSE\t/\tFALSE\t0\t__Secure-A8\t8\n"
            + "127.0.0.1\tFALSE\t/\tTRUE\t0\t__Host-A9\t9\n"
            + "127.0.0.1\tFALSE\t/p\tTRUE\t0\t__Host-A10\t10\n"
            + "127.0.0.1\tTRUE\t/\tTRUE\t0\t__Host-A11\t11\n"
            + "127.0.0.1\tFALSE\t/\tFALSE\t-5\tA12\t12\n"
            + "127.0.0.1\tFALSE\t/\tFALSE\t+7\tA13\t13\n"
            + "127.0.0.1\tFALSE\t/\tFALSE\t0\t\t14\n"
            + "\tFALSE\t/\tFALSE\t0\tA15\t15\n"
            + "127.0.0.1\tFALSE\t/\tFALSE\t0\tA16\t1\t6\n"
            + "127.0.0.1\tTRU\t/\tFALSE\t0\tA17\t17\n"
            + "127.0.0.1\tFALSE\t/\tFALSE\t0\tA18\t1 8 \n"
            + "  127.0.0.1\tFALSE\t/\tFALSE\t0\tA19\t19\n"

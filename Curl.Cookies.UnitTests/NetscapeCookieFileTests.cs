    /// <summary>Measured: the same file with <c>-j</c> keeps only the cookie with an expiry.</summary>
    [TestMethod]
    public void LoadCookieFile_DiscardSessionCookies_KeepsOnlyCookiesWithAnExpiry()
    {
        CookieStore store = Load(InTxt, discardSessionCookies: true);


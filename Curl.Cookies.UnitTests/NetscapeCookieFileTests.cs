    private CookieStore Load(string file, bool discardSessionCookies)
    {
        Diagnostics.ArrangeText("cookie file read in", file);
        Diagnostics.Arrange("discard session cookies", discardSessionCookies);
        Diagnostics.Arrange("clock Unix seconds", Now.ToUnixTimeSeconds());
        CookieStore store = new();
        store.LoadCookieFile(new StringReader(file), discardSessionCookies, Now);
        return store;
    }

    private string WriteJar(CookieStore store, DateTimeOffset now)
    {
        StringWriter writer = new() { NewLine = "\r\n" };
        store.WriteCookieJar(writer, now);
        string jar = writer.ToString();
        Diagnostics.ActText($"cookie jar written at Unix {now.ToUnixTimeSeconds()}", jar);
        return jar;
    }

    private void LogThrown(string call, Exception thrown)
    {
        Diagnostics.ActText($"{call} throws", thrown.GetType().Name + ": " + thrown.Message);
        Diagnostics.AssertText($"{call} exception type", nameof(ArgumentNullException), thrown.GetType().Name);
    }

    /// <summary>A cookie line of exactly <paramref name="length"/> characters named <paramref name="name"/>.</summary>
    private static string CookieLineOfLength(string name, int length)
    {
        string prefix = $"127.0.0.1\tFALSE\t/\tFALSE\t0\t{name}\t";
        return prefix + new string('u', length - prefix.Length);
    }

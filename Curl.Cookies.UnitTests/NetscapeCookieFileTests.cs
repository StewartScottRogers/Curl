    /// <summary>Measured: <c>curl -b te.txt -c -</c>. A later namesake (domain in any case) replaces an earlier one in its place.</summary>
    [TestMethod]
    public void LoadCookieFile_Namesakes_ReplaceInPlace()
    {
        const string File =
            "h\tFALSE\t/\tFALSE\t0\tX\t1\n"
            + "h\tFALSE\t/\tFALSE\t0\tY\t1\n"
            + "H\tFALSE\t/\tFALSE\t0\tX\t2\n"
            + "h\tTRUE\t/\tFALSE\t0\tX\t3\n";

        Assert.AreEqual(
            Header + ".h\tTRUE\t/\tFALSE\t0\tX\t3\r\nh\tFALSE\t/\tFALSE\t0\tY\t1\r\nH\tFALSE\t/\tFALSE\t0\tX\t2\r\n",
            WriteJar(Load(File, discardSessionCookies: false), Now));
    }

    /// <summary>
    /// Measured: a cookie line followed by <c>after</c>, loaded with <c>-b</c>. A line of up to 4998
    /// characters before its line feed, a carriage return counted, is read; a longer one ends the reading,
    /// so neither it nor anything after it is loaded. A last line without a line feed has the same limit.
    /// </summary>
    [TestMethod]
    [DataRow(4998, "\n", "after len")]
    [DataRow(4999, "\n", "")]
    [DataRow(4998, "\r\n", "after len")]
    [DataRow(4999, "\r\n", "")]
    public void Read_LongLine_StopsReadingPastTheLimit(int lengthBeforeLineFeed, string lineEnd, string expectedNames)
    {
        string line = CookieLineOfLength("len", lengthBeforeLineFeed - (lineEnd.Length - 1)) + lineEnd;
        string file = line + "127.0.0.1\tFALSE\t/\tFALSE\t0\tafter\t1" + lineEnd;

        IReadOnlyList<Cookie> cookies = NetscapeCookieFile.Read(new StringReader(file));

        Assert.AreEqual(expectedNames, string.Join(' ', cookies.Reverse().Select(cookie => cookie.Name)));
    }

    /// <summary>Measured: a last line with no line feed, after <c>before</c>, loads at 4998 characters and not at 4999.</summary>
    [TestMethod]
    [DataRow(4998, "len before")]
    [DataRow(4999, "before")]
    public void Read_LastLineWithoutLineFeed_HasTheSameLimit(int length, string expectedNames)
    {
        string file = "127.0.0.1\tFALSE\t/\tFALSE\t0\tbefore\t1\n" + CookieLineOfLength("len", length);

        IReadOnlyList<Cookie> cookies = NetscapeCookieFile.Read(new StringReader(file));

        Assert.AreEqual(expectedNames, string.Join(' ', cookies.Reverse().Select(cookie => cookie.Name)));
    }

    [TestMethod]
    public void Read_EmptyText_ReadsNothing()
    {
        Assert.IsEmpty(NetscapeCookieFile.Read(new StringReader(string.Empty)));
    }

    [TestMethod]
    public void ParseLine_HttpOnlyLine_ReadsEveryField()
    {
        Assert.AreEqual(
            new Cookie("n", "v", "example.test", true, "/p", true, true, 1234),
            NetscapeCookieFile.ParseLine("#HttpOnly_.example.test\tTRUE\t/p\tTRUE\t1234\tn\tv"));
    }

    [TestMethod]
    public void ParseLine_TooFewFieldsForAMadeUpPath_IsRefused()
    {
        Assert.IsNull(NetscapeCookieFile.ParseLine("h\tFALSE"));
    }

    [TestMethod]
    public void Write_CookiesInTheGivenOrder_UsesTheWritersLineEnding()
    {
        StringWriter writer = new() { NewLine = "\n" };

        NetscapeCookieFile.Write(writer, [new Cookie("a", "1", "h", false, "/", false, false, 0)]);

        Assert.AreEqual(Header.Replace("\r\n", "\n", StringComparison.Ordinal) + "h\tFALSE\t/\tFALSE\t0\ta\t1\n", writer.ToString());
    }

    [TestMethod]
    public void NullArguments_Throw()
    {
        Assert.ThrowsExactly<ArgumentNullException>(() => NetscapeCookieFile.Read(null!));
        Assert.ThrowsExactly<ArgumentNullException>(() => NetscapeCookieFile.ParseLine(null!));
        Assert.ThrowsExactly<ArgumentNullException>(() => NetscapeCookieFile.Write(null!, []));
        Assert.ThrowsExactly<ArgumentNullException>(() => NetscapeCookieFile.Write(new StringWriter(), null!));
        Assert.ThrowsExactly<ArgumentNullException>(() => NetscapeCookieFile.FormatLine(null!));
    }

    /// <summary>The measured <c>in.txt</c>.</summary>
    private const string InTxt =

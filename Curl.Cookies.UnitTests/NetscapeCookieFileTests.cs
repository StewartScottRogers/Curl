        + "#HttpOnly_127.0.0.1\tFALSE\t/\tFALSE\t0\tho\t1\n"
        + ".127.0.0.1\tTRUE\t/\tFALSE\t0\tdom\t2\n"
        + "127.0.0.1\tFALSE\t/\tFALSE\t4102444800\tpersist\t3\n"

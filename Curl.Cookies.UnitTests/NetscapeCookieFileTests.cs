namespace Curl.Cookies;

/// <summary>
/// Pins <see cref="NetscapeCookieFile"/> and <see cref="CookieStore"/>'s cookie-file members to curl 8.21.0
/// (<c>x86_64-w64-mingw32</c>, Schannel, libpsl), measured on 2026-09-26: curl loaded the file written here
/// with <c>-b</c> (or received the headers written here from <c>Record-CurlExchange.ps1</c>) and the
/// expected text is the <c>-c</c> jar it wrote, byte for byte; the Windows build ends jar lines with CR LF.
/// BL-221's Notes record each command.
/// </summary>
[TestClass]
public sealed class NetscapeCookieFileTests
{
    private const string Header =
        "# Netscape HTTP Cookie File\r\n# https://curl.se/docs/http-cookies.html\r\n# This file was generated by libcurl! Edit at your own risk.\r\n\r\n";

    private static readonly DateTimeOffset Now = DateTimeOffset.FromUnixTimeSeconds(1_790_460_351);

    /// <summary>
    /// Measured: <c>curl -c jar.txt http://localhost:18221/p/x</c>, the response setting <c>a=1; Path=/</c>,
    /// <c>h=2; HttpOnly; Path=/p</c>, <c>d=3; Domain=localhost; Max-Age=3600</c>, <c>s=4; Secure; HttpOnly</c>
    /// and <c>q="x y"</c>. Newest first, <c>#HttpOnly_</c> before the domain, a dot before a domain cookie's.
    /// </summary>
    [TestMethod]
    public void WriteCookieJar_ReceivedCookies_MatchesCurlsJarByteForByte()
    {
        DateTimeOffset received = DateTimeOffset.FromUnixTimeSeconds(1_790_463_538);
        CookieStore store = new();
        store.StoreFromResponse(
            new Uri("http://localhost:18221/p/x"),
            ["a=1; Path=/", "h=2; HttpOnly; Path=/p", "d=3; Domain=localhost; Max-Age=3600", "s=4; Secure; HttpOnly", "q=\"x y\""],
            received);

        Assert.AreEqual(
            Header
            + "localhost\tFALSE\t/p\tFALSE\t0\tq\t\"x y\"\r\n"
            + "#HttpOnly_localhost\tFALSE\t/p\tTRUE\t0\ts\t4\r\n"
            + ".localhost\tTRUE\t/p\tFALSE\t1790467138\td\t3\r\n"
            + "#HttpOnly_localhost\tFALSE\t/p\tFALSE\t0\th\t2\r\n"
            + "localhost\tFALSE\t/\tFALSE\t0\ta\t1\r\n",
            WriteJar(store, received));
    }

    /// <summary>Measured: <c>curl -c empty.txt</c> against a response with no cookie writes the 135-byte header alone.</summary>
    [TestMethod]
    public void WriteCookieJar_NoCookies_WritesTheHeaderAlone()
    {
        string jar = WriteJar(new CookieStore(), Now);

        Assert.AreEqual(Header, jar);
        Assert.AreEqual(135, jar.Length);
    }

    /// <summary>
    /// Measured: <c>curl -b in.txt -c out.txt http://127.0.0.1:18221/</c>. Comments and blank, malformed,
    /// eight-field and bad-expiry lines are skipped; six fields mean an empty value; <c>true</c> counts as
    /// <c>TRUE</c>; the file's last line is the jar's first.
    /// </summary>
    [TestMethod]
    public void LoadCookieFile_MixedLines_KeepsWhatCurlKeeps()
    {
        CookieStore store = Load(InTxt, discardSessionCookies: false);

        Assert.AreEqual(
            Header
            + "127.0.0.1\tFALSE\t/\tTRUE\t0\tlower\t7\r\n"
            + "127.0.0.1\tFALSE\t/\tFALSE\t0\tempty\t\r\n"
            + "127.0.0.1\tFALSE\t/\tFALSE\t0\tnoval\t\r\n"
            + "127.0.0.1\tFALSE\t/\tFALSE\t0\tsp ace\tv v\r\n"
            + "127.0.0.1\tFALSE\t/\tFALSE\t0\tsess\t4\r\n"
            + "127.0.0.1\tFALSE\t/\tFALSE\t4102444800\tpersist\t3\r\n"
            + ".127.0.0.1\tTRUE\t/\tFALSE\t0\tdom\t2\r\n"
            + "#HttpOnly_127.0.0.1\tFALSE\t/\tFALSE\t0\tho\t1\r\n",

    /// <summary>
    /// Measured: a cookie line followed by <c>after</c>, loaded with <c>-b</c>. A line of up to 4998
    /// characters before its line feed, a carriage return counted, is read; a longer one ends the reading,
    /// so neither it nor anything after it is loaded. A last line without a line feed has the same limit.
    /// </summary>
    [TestMethod]
    [DataRow(4998, "\n", "after len")]
    [DataRow(4999, "\n", "")]
    [DataRow(4998, "\r\n", "after len")]
    [DataRow(4999, "\r\n", "")]
    public void Read_LongLine_StopsReadingPastTheLimit(int lengthBeforeLineFeed, string lineEnd, string expectedNames)
    {
        string line = CookieLineOfLength("len", lengthBeforeLineFeed - (lineEnd.Length - 1)) + lineEnd;
        string file = line + "127.0.0.1\tFALSE\t/\tFALSE\t0\tafter\t1" + lineEnd;

        Diagnostics.Arrange("line length before the line feed", lengthBeforeLineFeed);
        Diagnostics.ArrangeText("line ending", lineEnd);
        Diagnostics.ArrangeText("cookie file read in", file);
        Diagnostics.Arrange("clock Unix seconds", Now.ToUnixTimeSeconds());

        IReadOnlyList<Cookie> cookies = NetscapeCookieFile.Read(new StringReader(file), Now);
        string actualNames = string.Join(' ', cookies.Reverse().Select(cookie => cookie.Name));

        Diagnostics.ActCookies("cookies read", cookies);
        Diagnostics.AssertText("names of the cookies read, oldest first", expectedNames, actualNames);
        Assert.AreEqual(expectedNames, actualNames);
    }


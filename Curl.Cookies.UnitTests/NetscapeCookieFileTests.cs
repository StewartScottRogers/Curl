            + "127.0.0.1\tFALSE\t/\tFALSE\t99999999999999999999\tA21\t21\n";

        CookieStore store = Load(File, discardSessionCookies: false);

        Assert.AreEqual(
            Header
            + "127.0.0.1\tFALSE\t/p\tFALSE\t0\tA20\t20\r\n"
            + "  127.0.0.1\tFALSE\t/\tFALSE\t0\tA19\t19\r\n"

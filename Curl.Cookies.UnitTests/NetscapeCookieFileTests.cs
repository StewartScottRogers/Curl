        + "127.0.0.1\tFALSE\t/\tFALSE\t0\tsp ace\tv v\n"
        + "127.0.0.1\tFALSE\t/\tFALSE\t0\tnoval\n"
        + "127.0.0.1\tFALSE\t/\tFALSE\t0\tempty\t\n"
        + "bad line\n"
        + "127.0.0.1\tFALSE\t/\tFALSE\tabc\tnum\t5\n"
        + "127.0.0.1\tFALSE\t/\tFALSE\t0\tseven\t6\textra\n"
        + "127.0.0.1\tfalse\t/\ttrue\t0\tlower\t7\n";

    private static CookieStore Load(string file, bool discardSessionCookies)
    {
        CookieStore store = new();
        store.LoadCookieFile(new StringReader(file), discardSessionCookies, Now);
        return store;
    }

    private static string WriteJar(CookieStore store, DateTimeOffset now)
    {
        StringWriter writer = new() { NewLine = "\r\n" };
        store.WriteCookieJar(writer, now);
        return writer.ToString();
    }

    /// <summary>A cookie line of exactly <paramref name="length"/> characters named <paramref name="name"/>.</summary>
    private static string CookieLineOfLength(string name, int length)
    {
        string prefix = $"127.0.0.1\tFALSE\t/\tFALSE\t0\t{name}\t";
        return prefix + new string('u', length - prefix.Length);
    }

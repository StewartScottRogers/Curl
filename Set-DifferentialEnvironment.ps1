<#
.SYNOPSIS
Sets the CURL_DIFFERENTIAL_* variables the differential tests read, for the calling session, with no interaction.

.DESCRIPTION
Dot-source it so the variables stay set in your session: ". .\Set-DifferentialEnvironment.ps1".
Sets, for the current session only:

  CURL_DIFFERENTIAL_REFERENCE          the reference curl.exe (curl 8.22.0, Schannel build)
  CURL_DIFFERENTIAL_REFERENCE_LIBRARY  the reference libcurl-4.dll, taken from the folder of that curl.exe
  CURL_DIFFERENTIAL_REFERENCE_LIBCURL  the same library (the libcurl scenario tests read this name)
  CURL_DIFFERENTIAL_PKI                the directory New-DifferentialPki.ps1 wrote

Without -ReferenceCurl it looks for a curl.exe whose "curl -V" reports "curl 8.22.0" and "Schannel":
first every curl.exe on PATH, then the "ucrt64\bin" and "mingw64\bin" folders of the MSYS2 (or Git for
Windows) root found from where bash.exe or pacman.exe lives. When none is found it stops with an error
naming what it looked for. It downloads nothing.

.PARAMETER ReferenceCurl
Path of the reference curl.exe; skips the search. Still must exist.

.PARAMETER ReferenceLibrary
Path of the reference libcurl; default is libcurl-4.dll beside the reference curl.exe.

.PARAMETER Pki
An existing directory of differential certificates; default is "%LOCALAPPDATA%\Curl\differential-pki",
generated by New-DifferentialPki.ps1 when it holds no ca.pem.

.EXAMPLE
. .\Set-DifferentialEnvironment.ps1
#>
[CmdletBinding()]
param([string]$ReferenceCurl, [string]$ReferenceLibrary, [string]$Pki)

$ErrorActionPreference = 'Stop'
$wantedVersion = 'curl 8.22.0'
$wantedTls = 'Schannel'

function Test-ReferenceCurl([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return $false }
    $ErrorActionPreference = 'Continue'
    try { $report = (& $Path -V 2>&1) -join "`n" } catch { return $false }
    return $report.Contains($wantedVersion) -and $report.Contains($wantedTls)
}

function Get-CandidateFolders {
    foreach ($entry in ($env:PATH -split [IO.Path]::PathSeparator)) { if ($entry) { $entry } }
    foreach ($tool in 'bash', 'pacman') {
        $found = Get-Command "$tool.exe" -ErrorAction SilentlyContinue | Select-Object -First 1
        if (-not $found) { continue }
        $folder = Split-Path -Parent $found.Source
        foreach ($root in @((Split-Path -Parent $folder), (Split-Path -Parent (Split-Path -Parent $folder)))) {
            if ($root) { Join-Path $root 'ucrt64\bin'; Join-Path $root 'mingw64\bin' }
        }
    }
}

if (-not $ReferenceCurl) {
    $searched = New-Object Collections.Generic.List[string]
    foreach ($folder in Get-CandidateFolders) {
        $candidate = Join-Path $folder 'curl.exe'
        if ($searched.Contains($candidate)) { continue }
        $searched.Add($candidate)
        if (Test-ReferenceCurl $candidate) { $ReferenceCurl = $candidate; break }
    }
    if (-not $ReferenceCurl) {
        throw "No curl.exe reporting '$wantedVersion' and '$wantedTls' in 'curl -V' was found. Looked in: the PATH folders, then the ucrt64\bin and mingw64\bin folders beside bash.exe or pacman.exe ($($searched.Count) candidates). Point at one with -ReferenceCurl <path to curl.exe> (and -ReferenceLibrary <path to libcurl-4.dll>)."
    }
}
elseif (-not (Test-Path -LiteralPath $ReferenceCurl -PathType Leaf)) {
    throw "No curl.exe reporting '$wantedVersion' and '$wantedTls' in 'curl -V' was found: -ReferenceCurl '$ReferenceCurl' does not exist. Point -ReferenceCurl at the reference curl.exe."
}
$ReferenceCurl = (Resolve-Path -LiteralPath $ReferenceCurl).Path

if (-not $ReferenceLibrary) { $ReferenceLibrary = Join-Path (Split-Path -Parent $ReferenceCurl) 'libcurl-4.dll' }
if (-not (Test-Path -LiteralPath $ReferenceLibrary -PathType Leaf)) {
    throw "The reference libcurl '$ReferenceLibrary' does not exist. Point -ReferenceLibrary at the libcurl-4.dll that belongs to the reference curl.exe."
}
$ReferenceLibrary = (Resolve-Path -LiteralPath $ReferenceLibrary).Path

if (-not $Pki) {
    $Pki = Join-Path $env:LOCALAPPDATA 'Curl\differential-pki'
    if (-not (Test-Path -LiteralPath (Join-Path $Pki 'ca.pem'))) { & (Join-Path $PSScriptRoot 'New-DifferentialPki.ps1') -Directory $Pki }
}
elseif (-not (Test-Path -LiteralPath $Pki -PathType Container)) {
    throw "The -Pki directory '$Pki' does not exist."
}
$Pki = (Resolve-Path -LiteralPath $Pki).Path

$env:CURL_DIFFERENTIAL_REFERENCE = $ReferenceCurl
$env:CURL_DIFFERENTIAL_REFERENCE_LIBRARY = $ReferenceLibrary
$env:CURL_DIFFERENTIAL_REFERENCE_LIBCURL = $ReferenceLibrary
$env:CURL_DIFFERENTIAL_PKI = $Pki
Write-Host "CURL_DIFFERENTIAL_REFERENCE=$ReferenceCurl"
Write-Host "CURL_DIFFERENTIAL_REFERENCE_LIBRARY=$ReferenceLibrary"
Write-Host "CURL_DIFFERENTIAL_REFERENCE_LIBCURL=$ReferenceLibrary"
Write-Host "CURL_DIFFERENTIAL_PKI=$Pki"

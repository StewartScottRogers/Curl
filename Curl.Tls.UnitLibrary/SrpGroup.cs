    /// <summary>Gets every group of Appendix A, smallest first.</summary>
    public static IReadOnlyList<SrpGroup> All { get; } = [Bits1024, Bits1536, Bits2048, Bits3072, Bits4096, Bits6144, Bits8192];

    /// <summary>Gets the prime N, big-endian, without leading zero bytes.</summary>
    public ReadOnlySpan<byte> Prime => prime;

    /// <summary>Gets the generator g, big-endian.</summary>
    public ReadOnlySpan<byte> Generator => generator;

    /// <summary>Gets the length of N in bytes, the width RFC 5054's <c>PAD()</c> pads to.</summary>
    public int PrimeLength => prime.Length;

    internal BigInteger PrimeValue { get; }

    internal BigInteger GeneratorValue { get; }

    /// <summary>
    /// Returns the group whose prime and generator have the values of
    /// <paramref name="prime" /> and <paramref name="generator" /> (leading zero bytes aside).
    /// </summary>
    /// <param name="prime">N as a ServerKeyExchange carries it.</param>
    /// <param name="generator">g as a ServerKeyExchange carries it.</param>
    /// <returns>The group, or <see langword="null" /> when the pair is not one of Appendix A's.</returns>
    public static SrpGroup? Find(ReadOnlySpan<byte> prime, ReadOnlySpan<byte> generator)
    {
        BigInteger primeValue = new(prime, isUnsigned: true, isBigEndian: true);
        BigInteger generatorValue = new(generator, isUnsigned: true, isBigEndian: true);
        return All.FirstOrDefault(group => group.PrimeValue == primeValue && group.GeneratorValue == generatorValue);
    }
}
